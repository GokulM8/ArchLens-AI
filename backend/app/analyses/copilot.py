"""Architecture Copilot over one stored analysis.

The LLM context is built only from the five deterministic artifacts in the
requested analysis's own directory (the caller has already checked its access
token), through the same VerifiedContextBuilder, prompts and guardrails as the
/llm endpoints. The answer is labelled as model output; it never replaces or
amends the deterministic results.
"""

from __future__ import annotations

import os
from typing import Any, Dict

from app.analyses.errors import APIError
from app.analyses.safeguards import llm_slot
from app.analyses.storage import AnalysisStore
from app.llm.context import VerifiedContextBuilder
from app.llm.factory import LLMProviderFactory
from app.llm.guardrails import GroundingGuardrails
from app.llm.redaction import redact
from app.llm.service import LLMService

DISCLOSURE = (
    "Answers are generated by an external language model from this analysis's "
    "deterministic results, which are sent to the configured LLM provider. "
    "They may be wrong; the analysis itself is the source of truth."
)

# Provider failure → (HTTP status, /v1 code).
_PROVIDER_ERRORS = {
    "provider_timeout": (504, "llm_timeout"),
    "provider_rate_limited": (503, "llm_provider_busy"),
    "provider_unavailable": (503, "llm_provider_unavailable"),
    "provider_unreachable": (503, "llm_provider_unavailable"),
}


def max_question_chars() -> int:
    try:
        return max(1, int(os.getenv("ARCHLENS_COPILOT_MAX_QUESTION_CHARS", "").strip() or 2000))
    except ValueError:
        return 2000


def copilot_status() -> Dict[str, Any]:
    """Whether the Copilot can answer; never includes the key or base URL."""
    error = LLMProviderFactory.get_configuration_error()
    return {
        "enabled": error is None,
        "provider": os.getenv("ARCHLENS_LLM_PROVIDER", "").lower() or None,
        "model": os.getenv("ARCHLENS_LLM_MODEL", "") or None,
        "configurationError": _safe(error) if error else None,
        "maxQuestionChars": max_question_chars(),
        "disclosure": DISCLOSURE,
    }


def _safe(text: Any) -> str:
    return redact(str(text), [os.getenv("ARCHLENS_LLM_API_KEY")])


async def ask(store: AnalysisStore, analysis_id: str, question: str, client: str) -> Dict[str, Any]:
    """Answer ``question`` about one analysis. The caller has checked its access token."""
    question = question.strip()
    if not question:
        raise APIError(422, "validation_error", "Ask a question.")
    if len(question) > max_question_chars():
        raise APIError(422, "question_too_long", f"Questions are limited to {max_question_chars()} characters.")

    view = store.view(analysis_id)  # 409 unless completed
    if view.get("empty"):
        raise APIError(409, "analysis_empty", "This analysis found no Python modules, so there is nothing to discuss.")

    config_error = LLMProviderFactory.get_configuration_error()
    if config_error:
        raise APIError(503, "llm_not_configured", f"The Copilot is not configured on this server: {_safe(config_error)}")

    try:
        builder = VerifiedContextBuilder.from_artifacts_dir(store.analysis_dir(analysis_id))
    except (FileNotFoundError, ValueError):
        raise APIError(409, "analysis_artifacts_missing", "This analysis has no artifacts for the Copilot to use.")

    service = LLMService(LLMProviderFactory, builder, GroundingGuardrails(builder))
    # Rate limits and quota count only requests that actually reach the provider.
    with llm_slot(client):
        result = await service.ask(question)

    error = result.error
    if not result.success:
        error_type = error.error_type if error else "provider_error"
        message = _safe(error.message if error else "The LLM provider returned no answer.")
        if error_type == "configuration_error":
            raise APIError(503, "llm_not_configured", f"The Copilot is not configured correctly: {message}")
        status, code = _PROVIDER_ERRORS.get(error_type, (502, "llm_provider_error"))
        raise APIError(
            status,
            code,
            f"The LLM provider could not answer: {message}",
            extra={"providerError": error_type, "retryable": bool(error and error.retriable)},
        )

    warning = error.message if error and error.error_type == "validation_warning" else None
    usage = result.metadata.usage
    return {
        "analysisId": analysis_id,
        "question": question,
        "answer": result.content,
        # False when the guardrails flagged claims they could not match to the artifacts.
        "grounded": warning is None,
        "groundingWarning": _safe(warning) if warning else None,
        "provider": result.metadata.provider,
        "model": result.metadata.model,
        "usage": {
            "promptTokens": usage.prompt_tokens,
            "completionTokens": usage.completion_tokens,
            "totalTokens": usage.total_tokens,
        },
        "latencyMs": round(result.metadata.latency_ms or 0.0),
        "disclosure": DISCLOSURE,
    }
